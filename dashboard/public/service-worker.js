/* Buddy AI PWA — offline shell + push notification hooks */
const CACHE = "buddy-pwa-v1";
const PRECACHE = ["/pwa", "/manifest.webmanifest"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(event.request).then((cached) => {
      const network = fetch(event.request)
        .then((response) => {
          if (response.ok && url.pathname.startsWith("/pwa")) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() => cached);
      return cached || network;
    }),
  );
});

self.addEventListener("push", (event) => {
  const data = event.data?.json?.() ?? { title: "Buddy", body: "I'm listening." };
  event.waitUntil(
    self.registration.showNotification(data.title || "Buddy", {
      body: data.body || "Your companion is here.",
      icon: "/favicon.ico",
      badge: "/favicon.ico",
    }),
  );
});
